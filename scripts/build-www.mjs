// Builds www/: the web bundle for hosting (PWA) and for the Capacitor store apps.
// Copies the game files, then stamps www/sw.js with the full precache list and a content-hash
// VERSION, which switches the service worker to cache-first release mode.
//
//   node scripts/build-www.mjs                  build www/
//   node scripts/build-www.mjs --patch-native   also lock landscape + fullscreen in android/ and ios/
//                                               (run after `npx cap add android|ios`; safe to repeat)
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'www');
const INCLUDE = ['index.html', 'styles.css', 'manifest.webmanifest', 'sw.js', 'icons', 'src', 'vendor'];
const SKIP = [/^icons\/store\//, /(^|\/)\.[^/]+$/, /\.map$/];                // store-listing art, dotfiles
const NO_PRECACHE = [/^sw\.js$/, /^icons\/icon(-maskable)?-512\.png$/];       // install-time only
const args = process.argv.slice(2);

function walk(rel) {
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) return [];
  if (fs.statSync(abs).isDirectory()) return fs.readdirSync(abs).sort().flatMap(n => walk(rel + '/' + n));
  return SKIP.some(re => re.test(rel)) ? [] : [rel];
}

// 1. copy
fs.rmSync(out, { recursive: true, force: true });
const files = INCLUDE.flatMap(walk);
let bytes = 0;
for (const f of files) {
  const dst = path.join(out, f);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(path.join(root, f), dst);
  bytes += fs.statSync(dst).size;
}

// 2. stamp the service worker
const precache = ['./', ...files.filter(f => !NO_PRECACHE.some(re => re.test(f)))];
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = 'afterzero-' + hash.digest('hex').slice(0, 12);
const swPath = path.join(out, 'sw.js');
let sw = fs.readFileSync(swPath, 'utf8');
const listRe = /\/\/ @precache-begin[^\n]*\n[\s\S]*?\/\/ @precache-end/;
if (!listRe.test(sw) || !/const VERSION = '[^']*';/.test(sw)) throw new Error('sw.js is missing its VERSION / @precache markers');
sw = sw.replace(/const VERSION = '[^']*';/, `const VERSION = '${version}';`)
  .replace(listRe, `// @precache-begin: generated by scripts/build-www.mjs\nconst PRECACHE = ${JSON.stringify(precache, null, 2)};\n// @precache-end`);
fs.writeFileSync(swPath, sw);
console.log(`www/: ${files.length} files, ${(bytes / 1048576).toFixed(2)} MB, ${precache.length} precached, service worker ${version}`);

// 3. native projects (optional): landscape only, no status bar, game-style window
if (args.includes('--patch-native')) patchNative();

function patchNative() {
  const manifest = path.join(root, 'android/app/src/main/AndroidManifest.xml');
  if (fs.existsSync(manifest)) {
    let x = fs.readFileSync(manifest, 'utf8');
    x = x.replace(/<activity([^>]*?)android:name="\.MainActivity"([^>]*?)>/, (m, a, b) => {
      let attrs = (a + 'android:name=".MainActivity"' + b).replace(/\s*android:screenOrientation="[^"]*"/, '');
      return `<activity${attrs} android:screenOrientation="sensorLandscape">`;
    });
    fs.writeFileSync(manifest, x);
    console.log('android: MainActivity locked to sensorLandscape');
  } else console.log('android/ not found (run `npx cap add android` first) - skipped');

  const plist = path.join(root, 'ios/App/App/Info.plist');
  if (fs.existsSync(plist)) {
    let x = fs.readFileSync(plist, 'utf8');
    const land = '<array>\n\t\t<string>UIInterfaceOrientationLandscapeLeft</string>\n\t\t<string>UIInterfaceOrientationLandscapeRight</string>\n\t</array>';
    const setKey = (key, value) => {
      const re = new RegExp(`<key>${key}</key>\\s*(<array>[\\s\\S]*?</array>|<true/>|<false/>|<string>[^<]*</string>)`);
      x = re.test(x) ? x.replace(re, `<key>${key}</key>\n\t${value}`) : x.replace(/<\/dict>\s*<\/plist>\s*$/, `\t<key>${key}</key>\n\t${value}\n</dict>\n</plist>\n`);
    };
    setKey('UISupportedInterfaceOrientations', land);
    setKey('UISupportedInterfaceOrientations~ipad', land);
    setKey('UIStatusBarHidden', '<true/>');
    setKey('UIViewControllerBasedStatusBarAppearance', '<false/>');
    setKey('UIRequiresFullScreen', '<true/>');
    fs.writeFileSync(plist, x);
    console.log('ios: Info.plist set to landscape, status bar hidden, full screen');
  } else console.log('ios/ not found (run `npx cap add ios` first) - skipped');
}
